<?php

declare(strict_types=1);

namespace App\Blog\Domain\Repository;

use App\Blog\Domain\Entity\Post;
use App\Blog\Domain\ValueObject\PostId;

/**
 * Хранилище статей со стороны записи.
 *
 * Интерфейс намеренно узкий: чтение идёт через query-сервисы, поэтому здесь
 * остались только операции, меняющие данные.
 */
interface PostRepositoryInterface
{
    /**
     * Сохраняет статью вместе со связями с категориями.
     *
     * Одной транзакцией: строка статьи, её категории и перестройка проекции
     * по накопленным событиям. События забираются через releaseEvents() после
     * записи, но до коммита — проекция обязана меняться вместе с данными.
     *
     * Новой статье проставляет идентификатор, выданный базой.
     */
    public function save(Post $post): void;

    /**
     * Увеличивает счётчик просмотров на единицу.
     *
     * Отдельный метод, а не save() после Post::registerView(): чтение строки,
     * прибавление в PHP и запись обратно теряют параллельные показы. Здесь
     * выполняется атомарный UPDATE ... views = views + 1, ради которого
     * агрегат грузить не нужно и не следует.
     */
    public function incrementViews(PostId $postId): void;
}
